#!/usr/bin/env python3
"""Regenerate Formula/*.rb from apps.json and upstream GitHub releases.

Constitution (specs/constitution.md):
- Formulas are generated artifacts; never edit them by hand.
- `version` is derived from the release asset FILENAME (source of truth).
  If the git tag disagrees, or the expected asset / checksum is missing,
  that app fails loudly and its existing formula is left untouched.
- Checksums come only from the release's SHA256SUMS.txt.

Usage:
  python3 script/update.py           # regenerate formulas
  python3 script/update.py --check   # CI drift check: exit 1 if any formula would change
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
APPS_JSON = REPO_ROOT / "apps.json"
FORMULA_DIR = REPO_ROOT / "Formula"

SEMVER_RE = re.compile(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$")
ASSET_RE_TMPL = r"^{app}-cli-(.+)-macos-universal\.zip$"

FORMULA_TEMPLATE = """\
# frozen_string_literal: true

# Auto-generated by script/update.py from apps.json + upstream GitHub releases.
# Do not edit by hand; see specs/constitution.md (Generated, not hand-edited).

class {class_name} < Formula
  desc "{desc}"
  homepage "https://github.com/{org}/{app}"

  # url must stay in lockstep with the upstream release — the asset name embeds
  # the version (the tag is verified against it by script/update.py).
  url "https://github.com/{org}/{app}/releases/download/v{version}/{app}-cli-{version}-macos-universal.zip"
  sha256 "{sha256}"

  # Per the NOTICE shipped inside the release asset:
  # "Licensed under the MIT License or the Apache License, Version 2.0, at your option."
  license any_of: ["MIT", "Apache-2.0"]

  depends_on :macos

  def install
    # Homebrew's zip unpack strategy strips the single top-level versioned
    # directory, so the payload sits directly in the buildpath.
    bin.install "{app}-cli"
    doc.install "README.md"
    # License compliance: ship every text the asset carries (the set varies
    # slightly between apps — NOTICE and a licenses/ dir are optional).
    (doc/"licenses").install "LICENSE-MIT", "LICENSE-APACHE"
    (doc/"licenses").install "NOTICE" if File.exist?("NOTICE")
    (doc/"licenses/fonts").install Dir["OFL-*.txt"]
    (doc/"licenses/fonts").install Dir["licenses/*"] if Dir.exist?("licenses")
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/{app}-cli --version")
  end
end
"""


def fail(msg: str) -> None:
    raise RuntimeError(msg)


def gh_api(path: str) -> dict:
    """GitHub API GET. Prefers authenticated `gh`, falls back to unauthenticated."""
    if shutil.which("gh"):
        result = subprocess.run(
            ["gh", "api", path],
            capture_output=True, text=True, check=True, timeout=60,
        )
        return json.loads(result.stdout)
    request = urllib.request.Request(f"https://api.github.com/{path}")
    request.add_header("Accept", "application/vnd.github+json")
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.loads(response.read().decode())


def download_text(url: str) -> str:
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read().decode()


def class_name_for(app: str) -> str:
    # Homebrew rule: formula file <app>-cli.rb -> class <App>Cli
    return "".join(part.capitalize() for part in f"{app}-cli".split("-"))


def fetch_release(app: str, org: str) -> dict:
    """Return {version, sha256} for the app's latest release, fail-closed."""
    release = gh_api(f"repos/{org}/{app}/releases/latest")
    tag = release.get("tag_name", "")
    assets = release.get("assets", [])

    pattern = re.compile(ASSET_RE_TMPL.format(app=re.escape(app)))
    matching = [a for a in assets if pattern.fullmatch(a.get("name", ""))]
    if not matching:
        fail(f"{app}: no asset matching {ASSET_RE_TMPL.format(app=app)} in release {tag}")

    asset = matching[0]
    version = pattern.fullmatch(asset["name"]).group(1)
    if not SEMVER_RE.fullmatch(version):
        fail(f"{app}: version '{version}' parsed from asset name is not semver")

    # Tag is advisory; asset filename is the source of truth (constitution §3).
    if tag.lstrip("vV") != version:
        fail(f"{app}: tag '{tag}' disagrees with asset version '{version}' — refusing to generate")

    sums_url = next(
        (a["browser_download_url"] for a in assets if a.get("name") == "SHA256SUMS.txt"), None
    )
    if not sums_url:
        fail(f"{app}: release {tag} has no SHA256SUMS.txt")

    expected_name = f"{app}-cli-{version}-macos-universal.zip"
    sha256 = None
    for line in download_text(sums_url).splitlines():
        line = line.strip()
        if not line:
            continue
        digest, _, filename = line.partition("  ")
        if filename.strip() == expected_name:
            sha256 = digest.strip()
            break
    if not sha256 or not re.fullmatch(r"[0-9a-f]{64}", sha256):
        fail(f"{app}: no valid sha256 for '{expected_name}' in SHA256SUMS.txt")

    return {"app": app, "org": org, "version": version, "sha256": sha256,
            "tag": tag, "asset": expected_name}


def render_formula(info: dict, desc: str) -> str:
    return FORMULA_TEMPLATE.format(
        class_name=class_name_for(info["app"]),
        desc=desc,
        org=info["org"],
        app=info["app"],
        version=info["version"],
        sha256=info["sha256"],
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="CI mode: exit 1 if any formula would change; write nothing")
    args = parser.parse_args()

    config = json.loads(APPS_JSON.read_text())
    org = config["github_org"]
    descriptions = config.get("descriptions", {})

    FORMULA_DIR.mkdir(exist_ok=True)

    statuses, errors = [], []
    for app in config["apps"]:
        try:
            info = fetch_release(app, org)
            desc = descriptions.get(app)
            if not desc:
                fail(f"{app}: no description in apps.json")
            if len(desc) > 100:
                fail(f"{app}: description longer than 100 chars")

            formula_path = FORMULA_DIR / f"{app}-cli.rb"
            rendered = render_formula(info, desc)

            if args.check:
                current = formula_path.read_text() if formula_path.exists() else ""
                drift = current != rendered
                statuses.append(f"{'DRIFT ' if drift else 'OK    '} {app}-cli {info['version']} ({info['tag']})")
                if drift:
                    errors.append(f"{app}: committed formula drifts from generator output")
            else:
                if formula_path.exists() and formula_path.read_text() == rendered:
                    statuses.append(f"OK     {app}-cli {info['version']} ({info['tag']}) (unchanged)")
                else:
                    formula_path.write_text(rendered)
                    statuses.append(f"WROTE  {app}-cli {info['version']} ({info['tag']})")
        except Exception as error:  # noqa: BLE001 — fail closed per app, keep going
            errors.append(str(error))
            statuses.append(f"FAILED {app}: {error}")

    print("\n".join(statuses))
    if errors:
        print(f"\n{len(errors)} app(s) failed:", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
